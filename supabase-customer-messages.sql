-- AFTER cloud customer chat: run in Supabase SQL Editor.
-- Enable Anonymous Sign-Ins in Authentication -> Sign In / Providers -> Anonymous.
create table if not exists public.customer_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  visitor_id text not null,
  customer_name text not null check (char_length(trim(customer_name)) between 1 and 120),
  customer_contact text not null check (char_length(trim(customer_contact)) between 1 and 200),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  sender text not null default 'customer' check (sender in ('customer','admin')),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.customer_messages add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.customer_messages add column if not exists is_read boolean not null default false;
create index if not exists customer_messages_created_at_idx on public.customer_messages(created_at desc);
create index if not exists customer_messages_user_id_created_at_idx on public.customer_messages(user_id,created_at);
alter table public.customer_messages enable row level security;
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade, created_at timestamptz not null default now());
alter table public.admin_users enable row level security;
revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;
drop policy if exists "Admins can check own admin record" on public.admin_users;
create policy "Admins can check own admin record" on public.admin_users for select to authenticated using (user_id = auth.uid());
revoke all on public.customer_messages from anon, authenticated;
grant select, insert, update on public.customer_messages to authenticated;
drop policy if exists "Customers read own chat" on public.customer_messages;
create policy "Customers read own chat" on public.customer_messages for select to authenticated using (user_id = auth.uid() or exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Customers send own chat messages" on public.customer_messages;
create policy "Customers send own chat messages" on public.customer_messages for insert to authenticated with check ((user_id=auth.uid() and sender='customer') or (sender='admin' and exists(select 1 from public.admin_users a where a.user_id=auth.uid())));
drop policy if exists "Admins mark messages read" on public.customer_messages;
create policy "Admins mark messages read" on public.customer_messages for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
